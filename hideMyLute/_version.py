"""Версионирование hideMyLute — единый источник версии приложения.

Схема версий — семантическое версионирование MAJOR.MINOR.PATCH:

- **MAJOR** — несовместимые изменения формата футера или публичного API.
- **MINOR** — новые возможности (новая функция, новая вкладка UI).
- **PATCH** — количество изменений (исправлений и доработок) с момента
  предыдущего минорного релиза.

Версия 2.0.4 соответствует четырём изменениям с релиза v2.0.0:

1. ``fix``: значения по умолчанию в полях ``AppConfig`` (df607d0)
2. ``feat``: оценка надёжности пароля и переключение языка (0af1dfe)
3. ``fix``: выравнивание вкладки «Соединение», статус-бар, переводы (f90a171)
4. ``build``: автономный исполняемый файл (PyInstaller onefile), launcher.py

История изменений ведётся в ``CHANGELOG.md``. При каждом новом изменении
PATCH увеличивается на 1; при появлении новой возможности увеличивается
MINOR, а PATCH сбрасывается в 0.
"""

from __future__ import annotations

__all__ = [
    "VERSION",
    "VERSION_MAJOR",
    "VERSION_MINOR",
    "VERSION_PATCH",
    "VERSION_STRING",
]

VERSION_MAJOR: int = 2
"""Основная версия — несовместимые изменения формата/API."""

VERSION_MINOR: int = 0
"""Минорная версия — новые возможности с предыдущего релиза."""

VERSION_PATCH: int = 4
"""Количество изменений с предыдущего минорного релиза."""

VERSION: tuple[int, int, int] = (
    VERSION_MAJOR,
    VERSION_MINOR,
    VERSION_PATCH,
)
"""Кортеж компонентов версии (MAJOR, MINOR, PATCH)."""

VERSION_STRING: str = ".".join(str(part) for part in VERSION)
"""Строковое представление версии: ``MAJOR.MINOR.PATCH``."""
